/**
 * feeds/index.mjs - server-side feed orchestration.
 *
 * Responsibilities:
 *   - run the live source chain with a timeout budget,
 *   - validate + recompute client-fetched ("browser direct") payloads so the
 *     browser can never hand the agents a malformed or invented snapshot,
 *   - build manual snapshots from typed-in numbers (user-verified data),
 *   - build clearly watermarked DEMO snapshots for testing the rules.
 *
 * Every snapshot carries an honest `dataQuality` label. The agents never see a
 * number without knowing where it came from.
 */

import { computeMetrics, normalizeCandles } from '../shared/feedcore.mjs';
import { fetchMarketData, fetchPredictionMarkets, searchMarkets } from '../shared/livesources.mjs';

export const DATA_QUALITY = {
  LIVE_SERVER: 'LIVE (server fetch)',
  LIVE_BROWSER: 'LIVE (browser direct fetch)',
  MANUAL: 'USER-PROVIDED (typed in by the operator)',
  DEMO: 'DEMO - generated by the app, NOT real market data',
};

export const MAX_INGEST_CANDLES = 1000;

function sanitizeTicker(t) {
  if (!t || typeof t !== 'object') return null;
  const num = (v) => (Number.isFinite(Number(v)) ? Number(v) : null);
  return {
    price: num(t.price),
    change24hPct: num(t.change24hPct),
    change1hPct: num(t.change1hPct),
    high24h: num(t.high24h),
    low24h: num(t.low24h),
    volume24hUsd: num(t.volume24hUsd),
    marketCapUsd: num(t.marketCapUsd),
    liquidityUsd: num(t.liquidityUsd),
    quote: typeof t.quote === 'string' ? t.quote.slice(0, 12) : null,
    displayName: typeof t.displayName === 'string' ? t.displayName.slice(0, 60) : null,
  };
}

export function buildSnapshot({ source, sourceLabel, pair, token, candles, ticker, fetchedAt, dataQuality, warnings = [], notes = [] }) {
  const cleanCandles = normalizeCandles(candles).slice(-MAX_INGEST_CANDLES);
  const cleanTicker = sanitizeTicker(ticker);
  const now = Date.now();
  const metrics = computeMetrics(cleanCandles, { now, ticker: cleanTicker });
  return {
    id: `SNP-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 6)}`,
    source,
    sourceLabel: sourceLabel || source,
    pair,
    token: token || pair,
    dataQuality,
    fetchedAt: fetchedAt || new Date(now).toISOString(),
    receivedAt: new Date(now).toISOString(),
    candles: cleanCandles,
    ticker: cleanTicker,
    metrics,
    warnings,
    notes,
  };
}

/** Server-side live lookup: walks the source chain. */
export async function liveSnapshot(pairInput, { preferredSource = null, timeoutMs = 7000 } = {}) {
  const result = await fetchMarketData(pairInput, { preferredSource, timeoutMs });
  if (!result.ok) {
    return { ok: false, attempts: result.attempts, message: result.message, code: 'LIVE_UNREACHABLE' };
  }
  const raw = result.raw;
  const snapshot = buildSnapshot({
    source: raw.source,
    sourceLabel: raw.sourceLabel,
    pair: raw.pair,
    token: raw.token,
    candles: raw.candles,
    ticker: raw.ticker,
    fetchedAt: raw.fetchedAt,
    dataQuality: DATA_QUALITY.LIVE_SERVER,
    warnings: raw.warnings,
  });
  return { ok: true, snapshot, attempts: result.attempts };
}

/**
 * Client-fetched payload (browser direct). The server re-derives every metric
 * from the raw candles; the client's own numbers are ignored.
 */
export function ingestClientSnapshot(payload, { trustLabel } = {}) {
  if (!payload || typeof payload !== 'object') {
    return { ok: false, code: 'BAD_PAYLOAD', message: 'No snapshot payload received.' };
  }
  const candles = normalizeCandles(payload.candles);
  if (candles.length > MAX_INGEST_CANDLES) candles.length = MAX_INGEST_CANDLES;
  const ticker = sanitizeTicker(payload.ticker);
  if (!candles.length && !ticker) {
    return { ok: false, code: 'EMPTY_PAYLOAD', message: 'Payload had neither candles nor a ticker; refusing to build a snapshot from nothing.' };
  }
  const warnings = Array.isArray(payload.warnings) ? payload.warnings.map((w) => String(w).slice(0, 240)).slice(0, 10) : [];
  const snapshot = buildSnapshot({
    source: String(payload.source || 'unknown').slice(0, 40),
    sourceLabel: `Browser direct fetch via ${payload.source || 'unknown'}`,
    pair: String(payload.pair || '').slice(0, 40),
    token: String(payload.token || payload.pair || '').slice(0, 24).toUpperCase(),
    candles,
    ticker,
    fetchedAt: payload.fetchedAt,
    dataQuality: trustLabel || DATA_QUALITY.LIVE_BROWSER,
    warnings,
    notes: ['Raw data was fetched by the browser (the server egress was blocked) and recomputed server-side.'],
  });
  return { ok: true, snapshot };
}

/**
 * Manual snapshot: the operator types verified numbers. Fields that were left
 * blank stay null and the agents treat them as "unknown" (never guessed).
 */
export function manualSnapshot(input) {
  const num = (v) => (v === '' || v === null || v === undefined ? null : Number.isFinite(Number(v)) ? Number(v) : null);
  const price = num(input.price);
  if (!Number.isFinite(price) || price <= 0) {
    return { ok: false, code: 'BAD_PRICE', message: 'A positive current price is required for a manual snapshot.' };
  }
  const ticker = sanitizeTicker({
    price,
    change24hPct: num(input.change24hPct),
    change1hPct: num(input.change1hPct),
    high24h: num(input.high24h),
    low24h: num(input.low24h),
    volume24hUsd: num(input.volume24hUsd),
    marketCapUsd: num(input.marketCapUsd),
    liquidityUsd: num(input.liquidityUsd),
    displayName: input.displayName,
  });

  const support = num(input.support);
  const resistance = num(input.resistance);
  const candleCount = 60;
  const candles = [];
  const stepMs = 5 * 60 * 1000;
  const nowBucket = Math.floor(Date.now() / stepMs) * stepMs;
  for (let i = candleCount - 1; i >= 0; i--) {
    candles.push({ t: nowBucket - i * stepMs, o: price, h: price, l: price, c: price, v: 0 });
  }
  const snapshot = buildSnapshot({
    source: 'manual',
    sourceLabel: 'Manual entry (operator-verified)',
    pair: input.token || 'MANUAL',
    token: String(input.token || 'MANUAL').toUpperCase(),
    candles,
    ticker,
    dataQuality: DATA_QUALITY.MANUAL,
    notes: [
      'Operator typed these numbers. Flat placeholder candles are attached only to satisfy structure checks; all candle-derived fields are marked unknown.',
    ],
  });

  const m = snapshot.metrics;
  m.manual = true;
  m.supplied = {
    r5: num(input.r5),
    r15: num(input.r15),
    r60: num(input.change1hPct),
    support,
    resistance,
  };
  if (m.supplied.r5 !== null) m.r5 = m.supplied.r5;
  if (m.supplied.r15 !== null) m.r15 = m.supplied.r15;
  if (m.supplied.r60 !== null) m.r60 = m.supplied.r60;
  if (support !== null) {
    m.support1h = support;
    m.distToSupportPct = ((price - support) / support) * 100;
  }
  if (resistance !== null) {
    m.resistance1h = resistance;
    m.distToResistancePct = ((resistance - price) / price) * 100;
  }
  m.candleFieldsUnknown = true;
  m.unknownFields = ['atrPct', 'stdev5mPct', 'volumeRatio', 'lastCandle', 'baseDetected', 'support (unless supplied)', 'resistance (unless supplied)'];
  snapshot.metrics = m;
  return { ok: true, snapshot };
}

/* ------------------------------------------------------------------ *
 * DEMO data - explicitly synthetic, for testing the rules engine
 * ------------------------------------------------------------------ */

function mulberry32(seed) {
  let a = seed >>> 0;
  return function rand() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const STEP_MS = 5 * 60 * 1000;
const N_CANDLES = 200;

function candle(t, open, close, rand, { volPct = 0.35, volBase = 100000, volMult = 1 } = {}) {
  const wick = Math.abs(close - open) * 0.5 + open * (volPct / 100) * 0.35;
  const hi = Math.max(open, close) + wick * rand();
  const lo = Math.min(open, close) - wick * rand();
  return { t, o: open, h: hi, l: lo, c: close, v: volBase * volMult * (0.7 + rand() * 0.6) };
}

/**
 * DEMO scenarios. Each one is constructed to exercise a specific rule, so you
 * can see whether the rules actually fire. They are NOT market data.
 *
 *   base     - order during an advance, then a tight coil under a real resistance
 *              → the Scanner should PASS and a paper ticket should be created
 *   pump     - a vertical three-candle move with volume
 *              → Anti-FOMO should BLOCK (the Scanner is designed not to)
 *   dump     - a steady decline
 *              → the Scanner should SKIP: long-only desks do not buy downtrends
 *   volatile - large two-way swings
 *              → the Scanner should SKIP on volatility
 */
export function demoSnapshot({ scenario = 'base', token = 'DEMO', seed = 42, priceStart = null } = {}) {
  const rand = mulberry32(seed + scenario.length * 7919);
  const nowBucket = Math.floor(Date.now() / STEP_MS) * STEP_MS;
  const candles = [];
  const T = (i) => nowBucket - (N_CANDLES - 1 - i) * STEP_MS;

  const build = {
    base() {
      let p = priceStart ?? 0.90;
      for (let i = 0; i < 140; i++) {
        const open = p;
        p = p * (1 + 0.0006 + (rand() * 2 - 1) * 0.0025);
        candles.push(candle(T(i), open, p, rand));
      }
      // a noisy range with a real ceiling above
      for (let i = 140; i < 190; i++) {
        const open = p;
        const pull = (1.005 - p) * 0.25; // mild mean reversion toward the ceiling
        p = p * (1 + pull + (rand() * 2 - 1) * 0.006);
        p = Math.max(0.985, Math.min(1.055, p));
        candles.push(candle(T(i), open, p, rand, { volPct: 0.5 }));
      }
      // the coil: a tight base the desk is allowed to trade
      for (let i = 190; i < N_CANDLES; i++) {
        const open = p;
        p = 1.0 * (1 + (rand() * 2 - 1) * 0.0016);
        candles.push(candle(T(i), open, p, rand, { volPct: 0.15, volMult: 0.75 }));
      }
    },
    pump() {
      let p = priceStart ?? 1.0;
      for (let i = 0; i < 196; i++) {
        const open = p;
        p = p * (1 + 0.0002 + (rand() * 2 - 1) * 0.0022);
        candles.push(candle(T(i), open, p, rand));
      }
      for (let i = 196; i < N_CANDLES; i++) {
        const open = p;
        p = p * 1.052; // vertical
        candles.push(candle(T(i), open, p, rand, { volPct: 1.2, volMult: 4 }));
      }
    },
    dump() {
      let p = priceStart ?? 1.0;
      for (let i = 0; i < N_CANDLES; i++) {
        const open = p;
        p = p * (1 - 0.0026 + (rand() * 2 - 1) * 0.0035);
        candles.push(candle(T(i), open, p, rand, { volMult: 1.1 }));
      }
    },
    volatile() {
      let p = priceStart ?? 1.0;
      for (let i = 0; i < N_CANDLES; i++) {
        const open = p;
        const swing = (rand() < 0.5 ? -1 : 1) * (0.02 + rand() * 0.055);
        p = p * (1 + swing);
        candles.push(candle(T(i), open, p, rand, { volPct: 6, volMult: 1.6 }));
      }
    },
  };

  (build[scenario] || build.base)();

  const last = candles[candles.length - 1];
  const first = candles[0];
  const ticker = {
    price: last.c,
    change24hPct: ((last.c - first.c) / first.c) * 100,
    high24h: Math.max(...candles.map((c) => c.h)),
    low24h: Math.min(...candles.map((c) => c.l)),
    volume24hUsd: 5_000_000,
    quote: 'USD',
    displayName: `${token}/USD`,
  };
  const snapshot = buildSnapshot({
    source: `demo:${scenario}`,
    sourceLabel: `DEMO generator (scenario: ${scenario})`,
    pair: `${token}-USD`,
    token,
    candles,
    ticker,
    dataQuality: DATA_QUALITY.DEMO,
    notes: [
      'These candles were generated by the app. They are NOT market data. Use them to test that the rules fire correctly, never as a result.',
    ],
  });
  return { ok: true, snapshot, scenario };
}

